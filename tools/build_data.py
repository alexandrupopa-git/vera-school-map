def recompute_primary(p):
    rec = [h for h in p['cutoff_history'] if isinstance(h.get('year'), int) and h['year'] >= FIRST_YEAR]
    full = [h['cutoff_km'] for h in rec if isinstance(h.get('cutoff_km'), (int, float)) and h['cutoff_km'] <= PRIMARY_MAX_REAL_KM and str(h.get('status', '')).startswith('Oversubscribed')]
    with_data = [h for h in rec if h.get('status') not in (None, '', 'No data')]
    if full:
        p['tightest_recent_cutoff_km'] = min(full); p['widest_recent_cutoff_km'] = max(full); p['comfort_radius_km'] = 0.75 * min(full)
        p['demand_status'] = 'Consistently oversubscribed' if len(full) == len(with_data) else 'Sometimes oversubscribed'
    elif with_data:
        p['tightest_recent_cutoff_km'] = None; p['widest_recent_cutoff_km'] = None
        nopub = [h for h in with_data if str(h.get('status', '')).startswith('Oversubscribed') and not isinstance(h.get('cutoff_km'), (int, float))]
        p['comfort_radius_km'] = 'no recent data' if nopub else 'no cut-off'
        p['demand_status'] = 'Oversubscribed – no distance published' if nopub else 'Spare places / all on-time offered'
    else:
        p['tightest_recent_cutoff_km'] = None; p['widest_recent_cutoff_km'] = None; p['comfort_radius_km'] = 'no recent data'; p['demand_status'] = 'No recent data'
def recompute_secondary(p):
    if isinstance(p.get('main_route_cutoff'), str) and p['main_route_cutoff'].startswith('rules:'): return  # rule-based: leave
    rec = [h['last_distance_km'] for h in p['allocation_history'] if isinstance(h.get('year'), int) and h['year'] >= FIRST_YEAR and isinstance(h.get('last_distance_km'), (int, float))]
    recent = [h for h in p['allocation_history'] if isinstance(h.get('year'), int) and h['year'] >= FIRST_YEAR]
    if rec: p['main_route_cutoff'] = min(rec)
    elif recent and any((h.get('oversubscribed') or '').lower() == 'no' for h in recent) and not any((h.get('oversubscribed') or '').lower() == 'yes' for h in recent): p['main_route_cutoff'] = 'everyone offered'
    elif isinstance(p.get('main_route_cutoff'), (int, float)): p['main_route_cutoff'] = 'no data'
