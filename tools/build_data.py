RICHMOND_STRAIGHT = ['Deer Park', "St Elizabeth", 'Thomson House']
def is_walking(p):
    dm = (p.get('distance_method') or '').lower()
    if 'walking' not in dm: return False
    for n in RICHMOND_STRAIGHT:
        if n.lower() in p['name'].lower(): return False
    return True

def ofsted_short(s):
    if not s: return 'No grade'
    s2 = s
    for k in ['Outstanding', 'Good', 'Requires improvement', 'Inadequate']:
        if k.lower() in s2.lower(): return k
    return 'Ungraded'

def short_selection(sel):
    s = sel.lower()
    if s.startswith('grammar'): return 'grammar'
    if s.startswith('partially'): return 'partially selective'
    if 'banded' in s and 'aptitude' in s: return 'comprehensive, banded + aptitude places'
    if 'banded' in s: return 'comprehensive, banded'
    if 'aptitude' in s: return 'comprehensive + aptitude places'
    return 'comprehensive'

