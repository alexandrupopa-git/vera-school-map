def jsfile(name, prop, obj):
    with open(os.path.join(OUT, name), 'w', encoding='utf-8') as f:
        f.write('// Generated by tools/build_data.py from source/ — do not edit by hand; edit the source files and rerun.\n')
        f.write('window.SM_DATA = window.SM_DATA || {};\n')
        f.write('window.SM_DATA.%s = ' % prop)
        json.dump(obj, f, ensure_ascii=False, separators=(',', ':'))
        f.write(';\n')

def num(x):
    if x is None or x == '': return None
    try: return float(x)
    except: return None

