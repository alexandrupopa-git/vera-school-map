"""Build data/*.js from the files in source/.

Run:  python3 tools/build_data.py
Each output file assigns one property on window.SM_DATA, so index.html can load
them with plain <script> tags (works from a double-clicked file as well as a web
server).  Edit the CSV / GeoJSON in source/ (e.g. add the 2027 cut-offs) and rerun.
Hand-maintained files (data/rules.js, data/config.js, data/extras.js,
data/stations.js) are NOT touched by this script.
"""
