def codes_in(text):
    """Return set of postcode districts and sectors mentioned in a free-text field."""
    out = set()
    text = text or ''
    # sectors like 'KT2 5/6', 'SW19 1/2/3', 'NW6 1/NW6 2', 'TW9 1, TW10 6', 'SW11 1/6'
    for m in re.finditer(r'\b([A-Z]{1,2}\d{1,2})\s+(\d(?:\s*/\s*\d)*)', text):
        d = m.group(1); out.add(d)
        for s in re.split(r'\s*/\s*', m.group(2)): out.add(f'{d} {s}')
    for m in re.finditer(r'\b([A-Z]{1,2}\d{1,2})\b', text):
        out.add(m.group(1))
    return out
